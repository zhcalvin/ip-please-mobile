#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const target = path.join(root, 'wechat/minigame/generated');
const sourceFiles = ['assets.js', 'en.js', 'i18n.js', 'gfx.js', 'sfx.js', 'docs.js', 'data.js', 'booth.js', 'events.js', 'screens.js', 'main.js'];
await fs.mkdir(path.join(target, 'assets'), { recursive: true });
await fs.mkdir(path.join(target, 'client'), { recursive: true });
const assetsSource = await fs.readFile(path.join(root, 'assets.js'), 'utf8');
const assetContext = { window: {} };
vm.runInNewContext(assetsSource, assetContext);
for (const [name, url] of Object.entries(assetContext.window.ASSET_IMAGES)) {
  const match = /^data:image\/png;base64,(.+)$/.exec(url);
  if (!match || !/^[a-z]+$/.test(name)) throw new Error(`Unexpected asset: ${name}`);
  await fs.writeFile(path.join(target, 'assets', `${name}.png`), Buffer.from(match[1], 'base64'));
  assetContext.window.ASSET_IMAGES[name] = `generated/assets/${name}.png`;
}
const parts = [];
for (const filename of sourceFiles) {
  let source = filename === 'assets.js'
    ? `window.ASSETS = ${JSON.stringify(assetContext.window.ASSETS)};\nconst ASSETS = window.ASSETS;\nwindow.ASSET_IMAGES = ${JSON.stringify(assetContext.window.ASSET_IMAGES)};`
    : await fs.readFile(path.join(root, filename), 'utf8');
  // Rename only the Mini Game's display titles; shared desktop/mobile rules stay canonical.
  if (filename === 'i18n.js' || filename === 'screens.js') {
    source = source
      .replaceAll("T('IP, PLEASE · 请出示你的 IP')", 'GAME_NAME')
      .replaceAll("T('IP, PLEASE 游戏画面')", "`${GAME_NAME} 游戏画面`")
      .replaceAll("T('请出示你的 IP')", 'GAME_NAME')
      .replaceAll("'IP, PLEASE'", 'GAME_NAME');
  }
  parts.push(`// ---- ${filename} ----\n${source}`);
}
for (const filename of ['branding.js', 'platform.js', 'ranking.js', 'ui.js', 'share.js', 'gameclub.js']) await fs.copyFile(path.join(root, 'wechat/client', filename), path.join(target, 'client', filename));
await fs.copyFile(path.join(root, 'wechat/shared/seed.js'), path.join(target, 'client/seed.js'));
for (const filename of ['LICENSE', 'OFL-fusion-pixel.txt']) await fs.copyFile(path.join(root, filename), path.join(target, filename));
const hooks = await fs.readFile(path.join(root, 'wechat/client/hooks.js'), 'utf8');
const bundle = `'use strict';\n// Generated by node wechat/tools/build.mjs. Root scripts share one lexical scope.\nmodule.exports = function start(wx, config, host) {\nconst { GAME_NAME } = require('./client/branding');\nconst { createPlatform } = require('./client/platform');\nconst platform = createPlatform(wx, host);\nconst { window, document, localStorage, navigator, Image, requestAnimationFrame, cancelAnimationFrame } = platform;\n${parts.join('\n\n')}\n\n${hooks}\n};\n`;
new vm.Script(bundle, { filename: 'game-bundle.js' });
await fs.writeFile(path.join(target, 'game-bundle.js'), bundle);
const files = await fs.readdir(path.join(target, 'assets'));
const bytes = (await Promise.all(files.map((name) => fs.stat(path.join(target, 'assets', name))))).reduce((n, st) => n + st.size, Buffer.byteLength(bundle));
console.log(`WeChat Mini Game built: ${path.relative(root, target)} (${files.length} PNGs, bundle + images ${(bytes / 1024).toFixed(1)} KiB)`);
